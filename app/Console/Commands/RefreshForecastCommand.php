<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Weather\Services\ForecastService;
use Illuminate\Console\Command;

/**
 * Refreshes the Open-Meteo forecast. Designed to run hourly. On failure the
 * previously stored forecast is retained so the display keeps working.
 */
class RefreshForecastCommand extends Command
{
    protected $signature = 'weather:forecast';

    protected $description = 'Fetch the Open-Meteo daily forecast and store it locally';

    public function handle(ForecastService $service): int
    {
        if (config('weather.demo_mode')) {
            $this->warn('Demo mode is enabled — forecast is generated by weather:demo.');

            return self::SUCCESS;
        }

        $result = $service->refresh();

        if (! $result['success']) {
            $this->error('Forecast refresh failed: '.$result['error']);

            return self::FAILURE;
        }

        $this->info(sprintf('Stored %d forecast day(s).', $result['days']));

        return self::SUCCESS;
    }
}
